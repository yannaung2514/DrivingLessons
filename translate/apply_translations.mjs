// Read and parse kanjidata.js
const content = fs.readFileSync(KANJI_FILE, 'utf8');
const start = content.indexOf('[');
const end = content.lastIndexOf(']');
const prefix = content.substring(0, start);
const suffix = content.substring(end + 1);
const data = JSON.parse(content.substring(start, end + 1));

let applied = 0;
let notFound = 0;

for (const item of data) {
    const needsTranslation = !item.myanmar ||
        item.myanmar.trim() === '' ||
        item.myanmar === item.english;

    if (needsTranslation && TRANSLATIONS[item.char]) {
        item.myanmar = TRANSLATIONS[item.char];
        applied++;
    } else if (needsTranslation) {
        console.warn(`⚠ No translation for ${item.char} (${item.english})`);
        notFound++;
    }
}

// Save
const output = prefix + JSON.stringify(data, null, 2) + suffix;
fs.writeFileSync(KANJI_FILE, output, 'utf8');

console.log(`✅ Applied ${applied} translations.`);
console.log(`⚠ Still missing: ${notFound}`);
console.log(`Remaining needing translation: ${data.filter(x => !x.myanmar || x.myanmar.trim() === '' || x.myanmar === x.english).length}`);