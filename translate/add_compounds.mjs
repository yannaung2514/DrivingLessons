// Add compound words to kanjidata.js
// Uses a curated dictionary of real Japanese compounds (compounds1.txt, compounds2.txt)
// with a fallback generator for kanji not in the dictionary.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const KANJI_FILE = path.join(__dirname, '..', 'kanjidata.js');

// Load compound dictionary from files
function loadCompounds() {
    const dict = {};
    for (let i = 1; i <= 5; i++) {
        const file = path.join(__dirname, `compounds${i}.txt`);
        if (!fs.existsSync(file)) continue;
        const lines = fs.readFileSync(file, 'utf8').split('\n');
        for (const line of lines) {
            const idx = line.indexOf('=');
            if (idx === -1) continue;
            const key = line.substring(0, idx).trim();
            const val = line.substring(idx + 1).trim();
            if (key && val) {
                dict[key] = val.split(',').map(w => w.trim()).filter(Boolean);
            }
        }
    }
    return dict;
}

