// Generate hiragana reading for a compound word
function getHiraganaForCompound(word, kanjiData) {
    // Check the HIRA dictionary first
    if (HIRA[word]) return HIRA[word];
    
    // Fallback: use the kanji's on reading (converted to hiragana)
    const on = kanjiData.on || '';
    const onHira = on.split(/[、,]/)[0]?.trim() || '';
    
    // Convert katakana to hiragana
    const katakanaToHiragana = (text) => text.replace(/[\u30a1-\u30f6]/g, ch =>
        String.fromCharCode(ch.charCodeAt(0) - 0x60)
    );
    
    return katakanaToHiragana(onHira);
}

// Main
const compoundsDict = loadCompounds();
console.log(`Compound dictionary loaded: ${Object.keys(compoundsDict).length} entries`);

const content = fs.readFileSync(KANJI_FILE, 'utf8');
const start = content.indexOf('[');
const end = content.lastIndexOf(']');
const prefix = content.substring(0, start);
const suffix = content.substring(end + 1);
const data = JSON.parse(content.substring(start, end + 1));

let withCurated = 0;
let withFallback = 0;
let withNone = 0;

for (const item of data) {
    const char = item.char;
    let compounds = [];

    // 1. Check curated dictionary
    if (CURATED[char]) {
        compounds = CURATED[char].slice(0, 5);
        withCurated++;
    }
    // 2. Check loaded compound files
    else if (compoundsDict[char]) {
        compounds = compoundsDict[char].slice(0, 5);
        withCurated++;
    }
    // 3. Fallback: generate from common patterns
    else {
        const generated = [];
        // Try prefix + kanji
        for (const p of COMMON_PREFIXES) {
            if (generated.length >= 3) break;
            const word = p + char;
            if (word.length >= 2 && word.length <= 4) {
                generated.push(word);
            }
        }
        // Try kanji + suffix
        for (const s of COMMON_SUFFIXES) {
            if (generated.length >= 5) break;
            const word = char + s;
            if (word.length >= 2 && word.length <= 4 && !generated.includes(word)) {
                generated.push(word);
            }
        }
        compounds = generated.slice(0, 5);
        if (compounds.length > 0) {
            withFallback++;
        } else {
            withNone++;
        }
    }

    // Add compounds field with hiragana readings
    item.compounds = compounds.map(word => ({
        word: word,
        hira: getHiraganaForCompound(word, item),
    }));
}

// Save
const output = prefix + JSON.stringify(data, null, 2) + suffix;
fs.writeFileSync(KANJI_FILE, output, 'utf8');

